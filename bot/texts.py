from html import escape

from aiogram import Bot

from .config import Config


async def invite_link(bot: Bot, teacher: dict, student_id: int | None = None) -> str:
    me = await bot.me()
    suffix = f"_{student_id}" if student_id else ""
    return f"https://t.me/{me.username}?start={teacher['student_secret']}{suffix}"


async def secrets_text(bot: Bot, teacher: dict) -> str:
    link = await invite_link(bot, teacher)
    return (
        "Ваши секреты:\n"
        "Вход учителя с других аккаунтов:\n"
        f"<code>{teacher['teacher_secret']}</code>\n"
        "Секрет для регистрации учеников:\n"
        f"<code>{teacher['student_secret']}</code>\n\n"
        "Общая ссылка-приглашение для учеников и родителей:\n"
        f"{link}\n\n"
        "💡 Удобнее личные ссылки: «👥 Ученики» → ученик → «Ссылка для ученика и родителей». "
        "По ней бот сразу узнаёт ученика."
    )


